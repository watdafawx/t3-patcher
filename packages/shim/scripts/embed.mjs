// Inlines packages/shim/src/shim.cjs into src/shim-source.generated.ts so that
// @t3p/shim can export the exact bytes the installer embeds in the replacement asar.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const source = readFileSync(new URL("../src/shim.cjs", import.meta.url), "utf8");
const out = new URL("../src/shim-source.generated.ts", import.meta.url);

const body = `// Generated by scripts/embed.mjs from src/shim.cjs. Do not edit.
export const SHIM_SOURCE: string = ${JSON.stringify(source)};
`;

writeFileSync(out, body, "utf8");
console.log(`embedded src/shim.cjs (${source.length} bytes) -> src/shim-source.generated.ts (${root})`);
